export function t(key, vars) {
  let text = DICT[locale.value]?.[key] ?? DICT.ru[key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

// Наборы строк (карусель загрузки): возвращает массив для текущего языка
export function tList(key) {
  return DICT[locale.value]?.[key] ?? DICT.ru[key] ?? []
}

